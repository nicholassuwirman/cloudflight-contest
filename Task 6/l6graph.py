"""Copy-graph DP (improved-plan-1 §3).

After an acceptance the relevant board is empty, so the state is just the slider config. Nodes are
post-acceptance configs (canonical: the two sliders of an axis are unordered), edges are single-copy
segments generated by l6multi.beam_multi. The best K-copy program is a min-weight K-edge path from start.
"""
import time
import numpy as np
from l6core import simulate_ref
from l6model import PatternModel
from l6multi import beam_multi
from l6solve import actions_to_program

INF = 10 ** 9


def canon_key(L, A):
    k = []
    for ax in range(3):
        c1 = (L[ax], A[ax])
        c2 = (L[ax + 3], A[ax + 3])
        k.append((c1, c2) if c1 <= c2 else (c2, c1))
    return tuple(k)


def swap_mask(rep, cur):
    """Mask m (bit ax) such that swapping sliders ax/ax+3 of rep gives cur."""
    (rL, rA), (cL, cA) = rep, cur
    m = 0
    for ax in range(3):
        if rL[ax] == cL[ax] and rA[ax] == cA[ax] and rL[ax + 3] == cL[ax + 3] and rA[ax + 3] == cA[ax + 3]:
            continue
        assert rL[ax] == cL[ax + 3] and rA[ax] == cA[ax + 3] and rL[ax + 3] == cL[ax] and rA[ax + 3] == cA[ax]
        m |= 1 << ax
    return m


def swap_act(act, m):
    if not m:
        return act
    for ax in range(3):
        if m >> ax & 1:
            a = (act >> (2 * ax)) & 3
            b = (act >> (2 * (ax + 3))) & 3
            act &= ~((3 << (2 * ax)) | (3 << (2 * (ax + 3))))
            act |= (b << (2 * ax)) | (a << (2 * (ax + 3)))
    return act


def swap_cfg(cfg, m):
    L, A = list(cfg[0]), list(cfg[1])
    for ax in range(3):
        if m >> ax & 1:
            L[ax], L[ax + 3] = L[ax + 3], L[ax]
            A[ax], A[ax + 3] = A[ax + 3], A[ax]
    return tuple(L), tuple(A)


def program_to_actions(prog, sign):
    acts = []
    for line in prog:
        a = 0
        for e in range(6):
            tok = line[e]
            if tok == '-':
                u = 0
            elif tok == 'T':
                u = 3
            else:
                up = (tok == 'F') == (sign[e] == 1)
                u = 1 if up else 2
            a |= u << (2 * e)
        acts.append(a)
    return acts


def apply_cfg(cfg, act):
    L, A = list(cfg[0]), list(cfg[1])
    for e in range(6):
        u = (act >> (2 * e)) & 3
        if u == 1:
            L[e] += 1
        elif u == 2:
            L[e] -= 1
        elif u == 3:
            A[e] ^= 1
    return tuple(L), tuple(A)


class CopyGraph:
    def __init__(self, case, pm=None):
        self.case = case
        self.pm = pm or PatternModel(case)
        self.K = case['K']
        R = case['R']
        self.start = (tuple([R] * 6), tuple([0] * 6))
        self.nodes = []        # rep exact config
        self.key2id = {}
        self.expanded = []     # expansion count
        self.esrc, self.edst, self.ew, self.eacts, self.eend = [], [], [], [], []
        self.edge_set = {}     # (src, dst) -> edge index with min weight
        self.log = None        # list -> every added segment (exact frame) is appended (ping-pong expansion)
        self.add_node(self.start)

    def add_node(self, cfg):
        k = canon_key(*cfg)
        if k in self.key2id:
            return self.key2id[k]
        i = len(self.nodes)
        self.key2id[k] = i
        self.nodes.append(cfg)
        self.expanded.append(0)
        return i

    def add_edge_exact(self, cfg_from, acts, cfg_to):
        """Add segment given in the exact frame of cfg_from."""
        if self.log is not None:
            self.log.append((cfg_from, list(acts)))
        s = self.add_node(cfg_from)
        m = swap_mask(self.nodes[s], cfg_from)
        acts = [swap_act(a, m) for a in acts]
        end = swap_cfg(cfg_to, m)
        d = self.add_node(end)
        w = len(acts)
        old = self.edge_set.get((s, d))
        if old is not None and self.ew[old] <= w:
            return
        if old is not None:
            self.ew[old] = w
            self.eacts[old] = acts
            self.eend[old] = end
            return
        self.edge_set[(s, d)] = len(self.esrc)
        self.esrc.append(s); self.edst.append(d); self.ew.append(w)
        self.eacts.append(acts); self.eend.append(end)

    def seed_program(self, prog):
        acts = program_to_actions(prog, self.pm.sign)
        acc = simulate_ref(self.case, prog)
        cfg = self.start
        prev = 0
        for t in acc:
            seg = acts[prev:t]
            c2 = cfg
            for a in seg:
                c2 = apply_cfg(c2, a)
            self.add_edge_exact(cfg, seg, c2)
            cfg, prev = c2, t

    def expand(self, nid, W, CAP, maxT, slack, MAXE, iB, iP, wS, wM, seed, jit=1):
        pm = self.pm
        L0 = np.array(self.nodes[nid][0], dtype=np.int64)
        A0 = np.array(self.nodes[nid][1], dtype=np.int64)
        n, dep, eL, eA, paths = beam_multi(pm.lineBits, pm.Pm, pm.Sm, pm.NW, pm.nP, pm.cellLine, pm.lm.nl,
                                           L0, A0, W, CAP, maxT, slack, MAXE, iB, iP, wS, wM, seed, jit)
        self.expanded[nid] += 1
        for q in range(n):
            d = int(dep[q])
            self.add_edge_exact(self.nodes[nid], [int(x) for x in paths[q, :d]],
                                (tuple(int(x) for x in eL[q]), tuple(int(x) for x in eA[q])))
        return n

    def dp(self):
        N = len(self.nodes)
        K = self.K
        src = np.array(self.esrc, dtype=np.int64)
        dst = np.array(self.edst, dtype=np.int64)
        w = np.array(self.ew, dtype=np.int64)
        f = np.full((K + 1, N), INF, dtype=np.int64)
        f[0, 0] = 0
        for k in range(K):
            cand = f[k][src] + w
            np.minimum.at(f[k + 1], dst, cand)
        return f, src, dst, w

    def best_path(self, f, src, dst, w):
        K = self.K
        y = int(np.argmin(f[K]))
        total = int(f[K, y])
        if total >= INF:
            return None, INF
        edges = []
        for k in range(K, 0, -1):
            ok = np.nonzero((dst == y) & (f[k - 1][src] + w == f[k, y]))[0]
            e = int(ok[0])
            edges.append(e)
            y = int(src[e])
        edges.reverse()
        return edges, total

    def build_program(self, edges):
        cfg = self.start
        acts = []
        for e in edges:
            s = self.esrc[e]
            m = swap_mask(self.nodes[s], cfg)
            acts += [swap_act(a, m) for a in self.eacts[e]]
            cfg = swap_cfg(self.eend[e], m)
        return actions_to_program(acts, self.pm.sign)


def solve_graph(case, incumbent=None, budget=30.0, maxExp=400, W=300, CAP=3000, Wstart=None, slack=2,
                MAXE=512, iB=4, iP=1, wS=0.05, wM=0.5, seed=1, alpha=0.8, verbose=False, pp=False):
    t0 = time.time()
    g = CopyGraph(case)
    K = case['K']
    if pp:
        # ping-pong expansion: every added segment also yields its reverse / replay variants (l6pp)
        from l6pp import SegSim, add_pp_edges
        g.log = []
        sim = SegSim(g.pm)
        seen = set()

        def pp_round():
            for _ in range(3):
                segs, g.log = g.log, []
                if not segs:
                    break
                add_pp_edges(g, sim, segs, seen)
            g.log = []
    else:
        def pp_round():
            pass
    if incumbent is not None:
        g.seed_program(incumbent)
    pm = g.pm
    R = case['R']
    maxT0 = 60 + 8 * pm.nP // 4 + 4 * R
    if incumbent is not None:
        maxT0 = min(maxT0, len(incumbent))
    # start node: first build (more endpoints)
    g.expand(0, Wstart or W, (Wstart or W) * 10, maxT0 + slack + 1, slack, MAXE, iB, iP, wS, wM, seed)
    pp_round()
    nexp = 1
    best_total = INF
    best_prog = None
    while True:
        f, src, dst, w = g.dp()
        edges, total = g.best_path(f, src, dst, w)
        if total < best_total:
            prog = g.build_program(edges)
            acc = simulate_ref(case, prog)
            assert len(acc) == K and acc[-1] == len(prog), (acc, len(prog), total)
            best_total, best_prog = total, prog
        if K == 1 or nexp >= maxExp or time.time() - t0 > budget:
            break
        # per-copy estimate from the incumbent
        Tfirst = int(f[1].min())
        cbar = alpha * max(1.0, (best_total - Tfirst) / max(1, K - 1))
        N = len(g.nodes)
        ks = np.arange(K)[:, None]
        pr = (f[:K] + (K - ks) * cbar).min(axis=0)
        pr = pr.astype(np.float64)
        exp = np.array(g.expanded, dtype=np.int64)
        pr[exp > 0] = np.inf
        pr[f[:K].min(axis=0) >= INF] = np.inf
        nid = int(np.argmin(pr))
        if not np.isfinite(pr[nid]) or pr[nid] >= best_total:
            break
        wmax = int(w.max()) if len(w) else maxT0
        g.expand(nid, W, CAP, min(wmax, best_total) + slack + 1, slack, MAXE, iB, iP, wS, wM, seed + nexp)
        pp_round()
        nexp += 1
    if verbose:
        print(f'graph: nodes={len(g.nodes)} edges={len(g.esrc)} exp={nexp} total={best_total} '
              f'{time.time() - t0:.1f}s')
    return best_prog
